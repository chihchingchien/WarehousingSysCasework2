# --------------------- Fixed paths and experiment --------------------- #
SCRIPT_DIR = Path(__file__).resolve().parent
SOURCE_DIR = SCRIPT_DIR.parent
FORECAST_FILE = SCRIPT_DIR / 'outputs' / 'future_daily_forecast.csv'
TASK2A_DIR = SCRIPT_DIR / 'task2a_outputs'
AUTONOMY_FILE = TASK2A_DIR / 'autonomy_targets_days.csv'
DAILY_TARGET_FILE = TASK2A_DIR / 'daily_target_stock_units.csv'
OUTPUT_DIR = SCRIPT_DIR / 'task2b_outputs'
REPLICATIONS = 100  # Change to 500 for final results (longer runtime).
SEED = 6203


def _key_r(x):
    return round(float(x), 6)


def main():
    parser = argparse.ArgumentParser(description='Task 2(b) simulation and charts')
    parser.add_argument('--plots-only', action='store_true',
                        help='Only generate charts from existing CSV results; skip simulation')
    args = parser.parse_args()
    if args.plots_only:
        generate_task2b_charts(OUTPUT_DIR)
        return
    for f in [FORECAST_FILE, AUTONOMY_FILE, DAILY_TARGET_FILE]:
        if not f.is_file():
            raise FileNotFoundError(f'Missing required input: {f}')
    if REPLICATIONS < 2:
        raise ValueError('REPLICATIONS must be >= 2 for confidence intervals')
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    forecast = load_forecast(FORECAST_FILE)
    sku_master = load_sku_master(SOURCE_DIR)
    sequences = load_supplier_sequences(SOURCE_DIR)
    calendar = load_replenishment_calendar(SOURCE_DIR)
    schedules, _ = build_calendar_maps(calendar)
    full_prob, partial_frac = load_supply_parameters(SOURCE_DIR)
    autonomy = pd.read_csv(AUTONOMY_FILE, dtype={'sku_id': str})
    autonomy['scenario_id'] = autonomy['scenario_id'].map(normalize_scenario)
    autonomy['service_target'] = autonomy['service_target'].map(_key_r)
    if autonomy.duplicated(['sku_id', 'scenario_id', 'service_target']).any():
        raise ValueError('Duplicate Task 2(a) autonomy policies')
    autonomy_map = {(r.sku_id, r.scenario_id, r.service_target): int(r.autonomy_days)
                    for r in autonomy.itertuples(index=False)}
    info = sku_master.set_index('sku_id')
    fg = {sid: g.sort_values('date').reset_index(drop=True)
          for sid, g in forecast.groupby('sku_id', sort=False)}
    start = forecast.date.min().normalize()
    if start < calendar.booking_datetime.min().normalize() or start > calendar.availability_datetime.max().normalize():
        raise ValueError('Forecast dates are outside generated replenishment calendar. Update load_replenishment_calendar date range.')

    # Read the ~2 million Task 2(a) rows in chunks, with carry for split SKUs.
    cols = ['sku_id', 'scenario_id', 'service_target', 'date', 'effective_day',
            'autonomy_days', 'target_stock_units']
    rng = np.random.default_rng(SEED)
    results = []
    seen = set()
    carry = pd.DataFrame(columns=cols)
    expected_days = None

    def process_sku(g):
        nonlocal expected_days
        sid = str(g['sku_id'].iloc[0])
        if sid in seen:
            raise ValueError(f'Non-contiguous SKU in daily target file: {sid}')
        seen.add(sid)
        if sid not in fg or sid not in info.index or sid not in sequences:
            raise ValueError(f'Missing forecast/master/supplier sequence for {sid}')
        sf = fg[sid]
        for (sc, R), policy in g.groupby(['scenario_id', 'service_target'], sort=True):
            key = (sid, sc, R)
            if key not in autonomy_map:
                raise ValueError(f'Unexpected Task 2(a) policy: {key}')
            D = autonomy_map[key]
            policy = policy.sort_values('date')
            n = len(policy)
            if expected_days is None:
                expected_days = n
            if n != expected_days or n < 1:
                raise ValueError(f'Incorrect target day count for {key}: {n}')
            dates = pd.to_datetime(policy['date']).to_numpy()
            wanted = pd.date_range(start, periods=n).to_numpy()
            if not np.array_equal(dates, wanted):
                raise ValueError(f'Dates mismatch for {key}')
            if not np.array_equal(policy['effective_day'].to_numpy(), np.arange(n)):
                raise ValueError(f'Effective day mismatch for {key}')
            if (policy['autonomy_days'].astype(int) != D).any():
                raise ValueError(f'Autonomy mismatch for {key}')
            if len(sf) < n or not np.array_equal(sf['date'].iloc[:n].to_numpy(), wanted):
                raise ValueError(f'Forecast days mismatch for {sid}')
            targets = policy['target_stock_units'].to_numpy(dtype=np.int64)
            if (targets < 0).any():
                raise ValueError(f'Negative target stock for {key}')
            r = simulate_policy_for_sku(sid, sc, R, D, targets, sf,
                                        info.loc[sid], sequences[sid], schedules,
                                        full_prob, partial_frac, start, n,
                                        REPLICATIONS, rng)
            results.append(r)

    for chunk in pd.read_csv(DAILY_TARGET_FILE, chunksize=25000, dtype={'sku_id': str}):
        if not carry.empty:
            chunk = pd.concat([carry, chunk], ignore_index=True)
        chunk['scenario_id'] = chunk['scenario_id'].map(normalize_scenario)
        chunk['service_target'] = chunk['service_target'].map(_key_r)
        last = str(chunk['sku_id'].iloc[-1])
        complete = chunk.loc[chunk['sku_id'] != last]
        carry = chunk.loc[chunk['sku_id'] == last].copy()
        for sid, group in complete.groupby('sku_id', sort=False):
            process_sku(group)
        if len(seen) and len(seen) % 200 == 0:
            print(f'Completed {len(seen)} SKUs', flush=True)
    if not carry.empty:
        process_sku(carry)
    if set(autonomy_map) != {(r['sku_id'], r['scenario_id'], r['service_target']) for r in results}:
        raise ValueError('Task 2(a) policy coverage does not match simulation output')

    result = pd.DataFrame(results).sort_values(['sku_id', 'scenario_id', 'service_target'])
    result.to_csv(OUTPUT_DIR / 'simulation_by_sku_policy.csv', index=False)
    policy = result.groupby(['scenario_id', 'service_target'], as_index=False).agg(
        sku_count=('sku_id', 'nunique'),
        mean_autonomy_days=('autonomy_days', 'mean'),
        expected_requested_units=('expected_requested_units', 'sum'),
        expected_served_units=('expected_served_units', 'sum'),
        expected_lost_units=('expected_lost_units', 'sum'),
        expected_avg_inventory_units=('expected_avg_inventory_units', 'sum'),
        expected_ending_inventory_units=('expected_ending_inventory_units', 'sum'),
        expected_ordered_units=('expected_ordered_units', 'sum'),
        expected_received_units=('expected_received_units', 'sum'),
        expected_primary_orders=('expected_primary_orders', 'sum'),
        expected_receipt_events=('expected_receipt_events', 'sum'),
        expected_fallback_units=('expected_fallback_units', 'sum'),
        expected_terminal_unfillable_units=('expected_terminal_unfillable_units', 'sum'),
        expected_stockout_days=('expected_stockout_days', 'sum'),
        avg_inventory_volume_m3=('avg_inventory_volume_m3', 'sum'),
    )
    policy['inventory_service'] = (policy['expected_served_units'] /
                                   policy['expected_requested_units'].replace(0, np.nan))
    policy['stockout_day_rate'] = policy['expected_stockout_days'] / (expected_days * policy['sku_count'])
    policy.to_csv(OUTPUT_DIR / 'policy_comparison.csv', index=False)
    assumptions = f'''Task 2(b) - baseline simulation assumptions
1. Evaluation starts on {start.date()} and lasts {expected_days} days, taken from Task 2(a) daily targets.
2. Opening on-hand inventory uses SKU Master; no initial outstanding purchase orders.
3. Each booking uses Task 2(a)'s target for the BOOKING DATE (not future receipt date).
4. Inventory position = on-hand + all outstanding scheduled supplier receipts.
5. Positive orders rounded UP to whole case packs and minimum inbound cases.
6. Actual supplier booking deadlines and 06:00 arrival dates follow Replenishment Scenarios CSV.
7. Booking before 10:00 occurs before daily demand; later booking after demand.
8. Supplier full-fill probability = {full_prob}; otherwise supplies {partial_frac} of whole cases (floor), with remainder sent to next DC's next receipt date. Fallback partial cases may be less than minimum inbound: treated as the residual of an existing order, not a new primary order.
9. Customer demand is lost-sales, not backordered. No replenishment during the order day.
10. Demand is independently sampled across days/SKUs from Task 1 Poisson/NB2 distributions; forecast and targets are fixed across replications.
11. Orders placed before the horizon ends but arriving after it remain outstanding; they count as ordered but not received during the horizon.
12. Fallback deliveries beyond horizon are not counted as received; report terminal_unfillable_units may include unresolved residuals at the horizon and is NOT a pure permanent supplier rejection measure.
13. No perishability, expiration, spoilage, or shelf-life rotation is modeled (limitation).
14. Existing Task 2(a) D is reused unchanged, even if it is a conservative fixed horizon rather than a dynamically changing actual next-delivery horizon (limitation).
15. Inventory service is fulfilled units / requested units. Robustness R is a target-stock quantile, NOT guaranteed realized service.
16. End-of-day on-hand inventory is averaged over days; initial on-hand not included in that time average.
17. Simulation replications={REPLICATIONS}; RNG seed={SEED}; 95% normal-approximation CI per SKU-policy for realized replication-level inventory service.
'''
    (OUTPUT_DIR / 'task2b_assumptions.txt').write_text(assumptions, encoding='utf-8')
    manifest = dict(seed=SEED, replications=REPLICATIONS, evaluation_days=expected_days,
                    evaluation_start=str(start.date()), skus=len(seen),
                    policies=len(result), full_fill_probability=full_prob,
                    partial_fill_fraction=partial_frac,
                    input_files=[str(FORECAST_FILE), str(AUTONOMY_FILE), str(DAILY_TARGET_FILE)],
                    outputs=['simulation_by_sku_policy.csv', 'policy_comparison.csv', 'task2b_assumptions.txt'])
    (OUTPUT_DIR / 'task2b_manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(f'Done: {len(result)} SKU-policy rows, {len(policy)} policy comparison rows.')
    print(f'Outputs: {OUTPUT_DIR}')
    generate_task2b_charts(OUTPUT_DIR)


if __name__ == '__main__':
    main()
