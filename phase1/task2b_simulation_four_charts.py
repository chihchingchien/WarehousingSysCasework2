def load_forecast(path: Path) -> pd.DataFrame:
    f = pd.read_csv(path)
    sku = find_col(f, ['sku_id'])
    date = find_col(f, ['date', 'demand_date'])
    mean = find_col(f, ['pred_mean', 'mean_units'])
    sd = find_col(f, ['pred_std', 'sd_units'])
    alpha = find_col(f, ['dispersion_alpha', 'alpha'], required=False)
    out = f[[sku, date, mean, sd] + ([alpha] if alpha else [])].copy()
    out.columns = ['sku_id', 'date', 'mean', 'sd'] + (['alpha'] if alpha else [])
    out['date'] = pd.to_datetime(out['date'])
    out = out.sort_values(['sku_id', 'date']).reset_index(drop=True)
    if out.duplicated(['sku_id', 'date']).any():
        raise ValueError('Forecast contains duplicate SKU-date rows.')
    if (out[['mean', 'sd']] < 0).any().any() or not np.isfinite(out[['mean', 'sd']]).all().all():
        raise ValueError('Forecast mean/sd must be finite and nonnegative.')
    if 'alpha' not in out:
        mu = out['mean'].to_numpy()
        var = np.square(out['sd'].to_numpy())
        out['alpha'] = np.where(mu > 1e-12, np.maximum((var - mu) / np.maximum(mu * mu, 1e-12), 0.0), 0.0)
    return out


def load_sku_master(source: Path) -> pd.DataFrame:
    p = find_file(source, 'QF_Facility_SKU_Master.csv')
    d = pd.read_csv(p)
    sku = find_col(d, ['sku_id'])
    case_pack = find_col(d, ['case_pack_units', 'case_pack', 'units_per_case', 'casepack'], required=False)
    min_cases = find_col(d, ['minimum_inbound_order_casepacks', 'minimum_inbound_cases', 'min_inbound_cases', 'minimum_order_cases'], required=False)
    min_units = find_col(d, ['minimum_inbound_quantity', 'minimum_inbound_units', 'min_inbound_units'], required=False)
    opening = find_col(d, ['opening_on_hand_units', 'opening_inventory_units', 'opening_inventory', 'initial_inventory_units'], required=False)
    volume = find_col(d, ['unit_volume_l', 'volume_l', 'product_volume_l', 'unit_volume_liters'], required=False)
    out = pd.DataFrame({'sku_id': d[sku].astype(str)})
    out['case_pack_units'] = 1 if case_pack is None else pd.to_numeric(d[case_pack], errors='raise').astype(int)
    if (out.case_pack_units <= 0).any():
        raise ValueError('case_pack_units must be positive.')
    if min_cases is not None:
        out['min_inbound_units'] = (pd.to_numeric(d[min_cases], errors='raise').astype(int) * out.case_pack_units)
    elif min_units is not None:
        out['min_inbound_units'] = pd.to_numeric(d[min_units], errors='raise').astype(int)
    else:
        warnings.warn('Minimum inbound quantity column not found; using one case as the minimum.')
        out['min_inbound_units'] = out.case_pack_units
    out['opening_inventory_units'] = 0 if opening is None else pd.to_numeric(d[opening], errors='coerce').fillna(0).astype(int)
    out['unit_volume_l'] = np.nan if volume is None else pd.to_numeric(d[volume], errors='coerce')
    return out


def load_supplier_sequences(source: Path) -> dict[str, list[str]]:
    p = find_file(source, 'QF_Facility_Supplier_Sequence.csv')
    d = pd.read_csv(p)
    sku = find_col(d, ['sku_id'])
    # Long form: sku_id, sequence/order/rank, dc/supplier.
    rank = find_col(d, ['sequence', 'sequence_rank', 'rank', 'supplier_rank', 'priority'], required=False)
    dc = find_col(d, ['dc_type', 'supplier_dc', 'supplier', 'dc'], required=False)
    seqs = {}
    if rank is not None and dc is not None:
        x = d[[sku, rank, dc]].copy()
        x[rank] = pd.to_numeric(x[rank], errors='raise')
        for sid, g in x.sort_values(rank).groupby(sku):
            seqs[str(sid)] = [normalize_dc(v) for v in g[dc].tolist()]
        return seqs
    # Wide form: preferred_dc, second_dc, third_dc.
    cols = []
    for aliases in [
        ['preferred_dc', 'primary_dc', 'first_dc'],
        ['second_dc', 'secondary_dc', 'dc_2'],
        ['third_dc', 'tertiary_dc', 'dc_3'],
    ]:
        c = find_col(d, aliases, required=False)
        if c is not None:
            cols.append(c)
    if not cols:
        raise KeyError(f'Cannot identify supplier sequence columns in {p}. Columns={d.columns.tolist()}')
    for row in d[[sku] + cols].itertuples(index=False, name=None):
        sid, vals = str(row[0]), row[1:]
        seqs[sid] = [normalize_dc(v) for v in vals if pd.notna(v) and str(v).strip()]
    return seqs


def _combine_date_time(date_series, time_series=None):
    dates = pd.to_datetime(date_series)
    if time_series is None:
        return dates
    # Handles HH:MM strings or full timestamps.
    raw = time_series.astype(str)
    full = pd.to_datetime(raw, errors='coerce')
    if full.notna().all() and full.dt.date.nunique() > 1:
        return full
    td = pd.to_timedelta(raw.where(raw.str.contains(':'), raw + ':00'), errors='coerce')
    if td.isna().any():
        raise ValueError('Could not parse time column.')
    return dates.dt.normalize() + td


def load_replenishment_calendar(source: Path) -> pd.DataFrame:
    """Expand rule-based supplier schedules into actual booking/receipt events."""
    p = find_file(source, 'QF_Facility_Replenishment_Scenarios.csv')
    rules = pd.read_csv(p)
    # Includes lead-in events and dates beyond the 112-day evaluation window.
    start = pd.Timestamp('2027-07-01')
    end = pd.Timestamp('2028-12-31')
    all_days = pd.date_range(start, end, freq='D')
    rows = []

    for rule in rules.itertuples(index=False):
        scenario = normalize_scenario(rule.scenario_id)
        dc = normalize_dc(rule.served_by_dc)
        label = str(rule.scheduled_days).strip().lower()
        anchor = (pd.Timestamp(rule.cycle_anchor_date).normalize()
                  if pd.notna(rule.cycle_anchor_date) else None)

        if label == 'every day':
            dates = all_days
        elif label == 'sunday and thursday':
            dates = all_days[all_days.dayofweek.isin([6, 3])]
        elif label == 'every monday':
            dates = all_days[all_days.dayofweek == 0]
        elif 'every other monday' in label:
            if anchor is None:
                raise ValueError(f'Missing cycle anchor for {scenario}/{dc}')
            dates = all_days[((all_days - anchor).days % 14) == 0]
        elif 'every fourth monday' in label:
            if anchor is None:
                raise ValueError(f'Missing cycle anchor for {scenario}/{dc}')
            dates = all_days[((all_days - anchor).days % 28) == 0]
        else:
            raise ValueError(f'Unknown scheduled_days value: {rule.scheduled_days}')

        for day in dates:
            booking_day = day - pd.Timedelta(days=int(rule.book_day_offset))
            booking_dt = pd.Timestamp(f'{booking_day.date()} {rule.book_time}')
            available_dt = pd.Timestamp(f'{day.date()} {rule.available_from}')
            rows.append((scenario, dc, booking_dt, available_dt))

    out = pd.DataFrame(rows, columns=[
        'scenario', 'dc_type', 'booking_datetime', 'availability_datetime'
    ]).drop_duplicates().sort_values([
        'scenario', 'dc_type', 'availability_datetime'
    ]).reset_index(drop=True)
    if (out.availability_datetime <= out.booking_datetime).any():
        raise ValueError('Availability must follow booking deadline.')
    return out


def load_supply_parameters(source: Path) -> tuple[float, float]:
    p = find_file(source, 'QF_Facility_Design_Parameters.csv')
    d = pd.read_csv(p)
    # Wide form first.
    for full_name, short in [('supply.full_fill_probability', 'full'), ('supply.partial_fill_fraction', 'partial')]:
        c = find_col(d, [full_name], required=False)
        if c is not None and len(d):
            val = float(pd.to_numeric(d[c], errors='coerce').dropna().iloc[0])
            if short == 'full':
                full_prob = val
            else:
                partial_frac = val
    if 'full_prob' in locals() and 'partial_frac' in locals():
        return full_prob, partial_frac
    # Supplied schema: parameter_group, parameter, value.
    group = find_col(d, ['parameter_group'], required=False)
    key = find_col(d, ['parameter', 'parameter_name', 'name', 'key'], required=False)
    val = find_col(d, ['value', 'parameter_value'], required=False)
    if key and val:
        kv = {}
        for _, row in d.iterrows():
            k = str(row[key]).strip()
            v = row[val]
            if pd.isna(v):
                continue
            kv[_norm(k)] = v
            if group and pd.notna(row[group]):
                kv[_norm(str(row[group]).strip() + '.' + k)] = v
        full_key = _norm('supply.full_fill_probability')
        partial_key = _norm('supply.partial_fill_fraction')
        if full_key in kv and partial_key in kv:
            full_prob, partial_frac = float(kv[full_key]), float(kv[partial_key])
            if not (0 <= full_prob <= 1 and 0 <= partial_frac <= 1):
                raise ValueError('Supply fill parameters must be between 0 and 1.')
            return full_prob, partial_frac
    raise ValueError('Supply fill parameters not found in Design Parameters CSV.')


# ----------------------------- autonomy logic ----------------------------- #

def effective_sequence(sequence: list[str], scenario: str) -> list[str]:
    seq = list(sequence)
    if scenario == 'Slow':
        # Case rule: no Local DC in Slow; Local-assigned products are supplied by Regional.
        seq = ['Regional' if x == 'Local' else x for x in seq]
    # De-duplicate while preserving order, because Local->Regional can create repeats.
    seen, out = set(), []
    for x in seq:
        if x not in seen:
            out.append(x); seen.add(x)
    return out


def build_calendar_maps(cal: pd.DataFrame):
    """Return schedules and the replenishment-driven protection period in days.

    At a booking deadline, inventory position is raised to cover demand until the
    NEXT receipt after the receipt associated with that booking. Therefore the
    protection period includes both supplier lead time and one replenishment cycle.
    """
    schedules = {}
    autonomy = {}
    for (sc, dc), g in cal.groupby(['scenario', 'dc_type']):
        g = g.sort_values('availability_datetime').reset_index(drop=True)
        schedules[(sc, dc)] = g
        if len(g) >= 2:
            next_avail = g.availability_datetime.shift(-1)
            # Last row: use the median inter-arrival interval to avoid dropping it.
            cycle = g.availability_datetime.diff().dropna().median()
            next_avail.iloc[-1] = g.availability_datetime.iloc[-1] + cycle
            protection = (next_avail - g.booking_datetime).dt.total_seconds() / 86400.0
        else:
            protection = (g.availability_datetime - g.booking_datetime).dt.total_seconds() / 86400.0
        autonomy[(sc, dc)] = max(1, int(math.ceil(float(protection.max()))))
    return schedules, autonomy


def next_availability_day(schedule: pd.DataFrame, after_dt: pd.Timestamp, eval_start: pd.Timestamp, n_days: int):
    cand = schedule.loc[schedule.availability_datetime > after_dt, 'availability_datetime']
    if cand.empty:
        return None
    day = int((cand.iloc[0].normalize() - eval_start.normalize()).days)
    return day if 0 <= day < n_days else None


# -------------------------- demand distribution --------------------------- #

def draw_daily_counts(mu, alpha, reps, rng):
    mu = np.asarray(mu, dtype=float)
    alpha = np.asarray(alpha, dtype=float)
    out = np.zeros((reps, len(mu)), dtype=np.int32)
    pois = alpha < 1e-10
    if pois.any():
        out[:, pois] = rng.poisson(mu[pois], size=(reps, pois.sum()))
    nb = ~pois
    if nb.any():
        size = 1.0 / alpha[nb]
        p = size / (size + mu[nb])
        out[:, nb] = rng.negative_binomial(size[None, :], p[None, :], size=(reps, nb.sum()))
    return out


def rolling_forward_sum(draws: np.ndarray, horizon: int, starts: int) -> np.ndarray:
    """reps x starts array of sum of next `horizon` days from each start."""
    c = np.pad(np.cumsum(draws, axis=1), ((0, 0), (1, 0)), constant_values=0)
    idx = np.arange(starts)
    end = idx + horizon
    if end.max() >= c.shape[1]:
        raise ValueError('Forecast buffer is too short for requested autonomy horizon.')
    return c[:, end] - c[:, idx]


def target_quantiles_for_sku(sku_forecast: pd.DataFrame, autonomy_days: set[int], service_targets, eval_days, target_reps, rng):
    mu = sku_forecast['mean'].to_numpy()
    alpha = sku_forecast['alpha'].to_numpy()
    draws = draw_daily_counts(mu, alpha, target_reps, rng)
    result = {}
    for D in sorted(autonomy_days):
        sums = rolling_forward_sum(draws, D, eval_days)
        for R in service_targets:
            # 'higher' returns a conservative observed discrete quantile.
            q = np.quantile(sums, R, axis=0, method='higher').astype(int)
            result[(D, float(R))] = q
    return result


# ----------------------------- ordering model ----------------------------- #

def round_order_units(need: np.ndarray, case_pack: int, minimum_units: int) -> np.ndarray:
    need = np.maximum(np.ceil(need).astype(int), 0)
    cases = np.ceil(need / case_pack).astype(int)
    min_cases = int(math.ceil(max(minimum_units, case_pack) / case_pack))
    cases = np.where(cases > 0, np.maximum(cases, min_cases), 0)
    return cases * case_pack


def booking_events_for_primary(schedule: pd.DataFrame, eval_start: pd.Timestamp, eval_days: int):
    """Map evaluation day -> list of (phase, booking_dt, arrival_dt)."""
    events = defaultdict(list)
    for row in schedule.itertuples(index=False):
        day = int((row.booking_datetime.normalize() - eval_start.normalize()).days)
        if not (0 <= day < eval_days):
            continue
        phase = 'morning' if row.booking_datetime.hour < 10 else 'evening'
        events[day].append((phase, row.booking_datetime, row.availability_datetime))
    return events


def simulate_policy_for_sku(
    sku_id: str,
    scenario: str,
    service_target: float,
    D: int,
    targets: np.ndarray,
    sku_forecast: pd.DataFrame,
    sku_info: pd.Series,
    sequence: list[str],
    schedules: dict,
    full_prob: float,
    partial_frac: float,
    eval_start: pd.Timestamp,
    eval_days: int,
    reps: int,
    rng: np.random.Generator,
):
    # Demand realization for Task 2 simulation.
    demand = draw_daily_counts(
        sku_forecast['mean'].to_numpy()[:eval_days],
        sku_forecast['alpha'].to_numpy()[:eval_days],
        reps, rng)
    on_hand = np.full(reps, int(sku_info.opening_inventory_units), dtype=np.int64)
    case_pack = int(sku_info.case_pack_units)
    minimum_units = int(sku_info.min_inbound_units)

    seq = effective_sequence(sequence, scenario)
    if not seq:
        raise ValueError(f'{sku_id}: empty supplier sequence for scenario {scenario}')
    primary = seq[0]
    if (scenario, primary) not in schedules:
        raise KeyError(f'{sku_id}: no replenishment calendar for {scenario}/{primary}')
    booking_events = booking_events_for_primary(schedules[(scenario, primary)], eval_start, eval_days)

    # scheduled[day] -> list of (ordered_qty_by_rep, sequence_index)
    scheduled = defaultdict(list)
    service_units = np.zeros(reps, dtype=np.int64)
    requested_units = np.zeros(reps, dtype=np.int64)
    lost_units = np.zeros(reps, dtype=np.int64)
    sum_inventory = np.zeros(reps, dtype=np.float64)
    ending_inventory = None
    primary_orders = np.zeros(reps, dtype=np.int64)
    receipt_events = np.zeros(reps, dtype=np.int64)
    ordered_units = np.zeros(reps, dtype=np.int64)
    received_units = np.zeros(reps, dtype=np.int64)
    fallback_units = np.zeros(reps, dtype=np.int64)
    terminal_unfillable = np.zeros(reps, dtype=np.int64)
    partial_events = np.zeros(reps, dtype=np.int64)
    stockout_days = np.zeros(reps, dtype=np.int64)

    def outstanding():
        if not scheduled:
            return np.zeros(reps, dtype=np.int64)
        total = np.zeros(reps, dtype=np.int64)
        for d, evs in scheduled.items():
            if d >= current_day:
                for qty, _ in evs:
                    total += qty
        return total

    def place_primary_order(day):
        inv_position = on_hand + outstanding()
        need = targets[day] - inv_position
        qty = round_order_units(need, case_pack, minimum_units)
        if not np.any(qty > 0):
            return
        # Associate this booking with the first primary availability after the booking datetime.
        # The booking event loop passes arrival day through closure below.
        return qty

    for current_day in range(eval_days):
        # 06:00 receipts / supplier fills.
        arrivals = scheduled.pop(current_day, [])
        for qty, seq_idx in arrivals:
            active = qty > 0
            if not np.any(active):
                continue
            full = rng.random(reps) < full_prob
            qty_cases = qty // case_pack
            partial_cases = np.floor(partial_frac * qty_cases).astype(np.int64)
            delivered = np.where(full, qty_cases, partial_cases) * case_pack
            delivered = np.minimum(delivered, qty)
            remainder = qty - delivered
            on_hand += delivered
            received_units += delivered
            receipt_events += (delivered > 0)
            partial_mask = active & (~full) & (remainder > 0)
            partial_events += partial_mask
            if np.any(remainder > 0):
                if seq_idx + 1 < len(seq):
                    next_dc = seq[seq_idx + 1]
                    sched = schedules.get((scenario, next_dc))
                    if sched is None:
                        terminal_unfillable += remainder
                    else:
                        after_dt = eval_start + pd.Timedelta(days=current_day, hours=6)
                        nd = next_availability_day(sched, after_dt, eval_start, eval_days)
                        if nd is None:
                            terminal_unfillable += remainder
                        else:
                            scheduled[nd].append((remainder.copy(), seq_idx + 1))
                            fallback_units += remainder
                else:
                    terminal_unfillable += remainder

        # Morning booking opportunities occur before customer demand.
        for phase, book_dt, arrival_dt in booking_events.get(current_day, []):
            if phase != 'morning':
                continue
            qty = place_primary_order(current_day)
            if qty is not None:
                arrival_day = int((arrival_dt.normalize() - eval_start.normalize()).days)
                if arrival_day >= 0:
                    scheduled[arrival_day].append((qty, 0))
                    primary_orders += (qty > 0)
                    ordered_units += qty

        # Customer demand during the order day; unmet demand is lost.
        d = demand[:, current_day].astype(np.int64)
        served = np.minimum(on_hand, d)
        on_hand -= served
        requested_units += d
        service_units += served
        lost_units += d - served
        stockout_days += (d > served)

        # Evening booking opportunities occur after customer demand.
        for phase, book_dt, arrival_dt in booking_events.get(current_day, []):
            if phase != 'evening':
                continue
            qty = place_primary_order(current_day)
            if qty is not None:
                arrival_day = int((arrival_dt.normalize() - eval_start.normalize()).days)
                if arrival_day >= 0:
                    scheduled[arrival_day].append((qty, 0))
                    primary_orders += (qty > 0)
                    ordered_units += qty

        sum_inventory += on_hand

    ending_inventory = on_hand.copy()
    inv_service = np.divide(service_units, requested_units, out=np.ones_like(service_units, dtype=float), where=requested_units > 0)
    volume_l = float(sku_info.unit_volume_l) if pd.notna(sku_info.unit_volume_l) else np.nan
    return {
        'sku_id': sku_id,
        'scenario_id': scenario,
        'service_target': service_target,
        'autonomy_days': D,
        'expected_inventory_service': float(inv_service.mean()),
        'expected_lost_units': float(lost_units.mean()),
        'expected_stockout_days': float(stockout_days.mean()),
        'stockout_day_rate': float(stockout_days.mean() / eval_days),
        'inventory_service_ci95_low': float(inv_service.mean() - 1.96 * inv_service.std(ddof=1) / np.sqrt(reps)) if reps > 1 else np.nan,
        'inventory_service_ci95_high': float(inv_service.mean() + 1.96 * inv_service.std(ddof=1) / np.sqrt(reps)) if reps > 1 else np.nan,
        'expected_requested_units': float(requested_units.mean()),
        'expected_served_units': float(service_units.mean()),
        'expected_avg_inventory_units': float((sum_inventory / eval_days).mean()),
        'expected_ending_inventory_units': float(ending_inventory.mean()),
        'expected_ordered_units': float(ordered_units.mean()),
        'expected_received_units': float(received_units.mean()),
        'expected_primary_orders': float(primary_orders.mean()),
        'expected_receipt_events': float(receipt_events.mean()),
        'expected_fallback_units': float(fallback_units.mean()),
        'expected_terminal_unfillable_units': float(terminal_unfillable.mean()),
        'expected_partial_fill_events': float(partial_events.mean()),
        'avg_inventory_volume_m3': float((sum_inventory / eval_days).mean() * volume_l / 1000.0) if np.isfinite(volume_l) else np.nan,
        'ending_inventory_volume_m3': float(ending_inventory.mean() * volume_l / 1000.0) if np.isfinite(volume_l) else np.nan,
    }





